package edu.pitt.cs;

/**
 * The cup sizes that a drink can be ordered in.
 */
public enum CupSize {
	/** A small cup, which costs the base price of the drink. */
	SMALL,
	/** A medium cup, which costs $0.50 more than a small cup. */
	MEDIUM,
	/** A large cup, which costs $1.00 more than a small cup. */
	LARGE
}
